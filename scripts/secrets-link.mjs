#!/usr/bin/env node
// pnpm secrets:link (08 §6): copy the API Worker's keys from the user-owned secrets file into
// apps/api/.dev.vars (gitignored) so `wrangler dev` sees them.
//
// - Source: $MATH_APP_SECRETS, else ~/.config/math-app-v1/secrets.env.
// - Only keys the Worker uses are written. GEMINI_API_KEY is build-time only and never reaches the Worker.
// - Never fails when the file is missing, and never prints a secret value (only key names).
import { chmodSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Keys the API Worker may read (07 §1). */
export const WORKER_KEYS = ['OPENAI_API_KEY', 'ANTHROPIC_API_KEY'];

/** @param {NodeJS.ProcessEnv} env */
export function secretsPath(env = process.env) {
  const override = env.MATH_APP_SECRETS?.trim();
  if (override) return resolve(override.replace(/^~(?=$|\/)/, homedir()));
  return join(homedir(), '.config', 'math-app-v1', 'secrets.env');
}

/**
 * Parse a dotenv-style file: KEY=value lines, optional `export `, `#` comments, optional quotes.
 * @param {string} text
 * @returns {Map<string, string>}
 */
export function parseEnv(text) {
  const out = new Map();
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const match = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!match) continue;
    const key = /** @type {string} */ (match[1]);
    let value = /** @type {string} */ (match[2]).trim();
    const quote = value[0];
    if (quote === '"' || quote === "'") {
      // A quoted value ends at its closing quote; anything after it (e.g. `# comment`) is ignored.
      const close = value.indexOf(quote, 1);
      if (close === -1) continue; // unterminated quote: skip the line rather than guess
      value = value.slice(1, close);
    } else {
      value = value.replace(/\s+#.*$/, '');
    }
    out.set(key, value);
  }
  return out;
}

/** Quote a value for .dev.vars (dotenv syntax) so spaces, '#' or quotes survive. */
function quote(value) {
  return JSON.stringify(value);
}

/**
 * @param {{ env?: NodeJS.ProcessEnv; target?: string; log?: (msg: string) => void }} [opts]
 * @returns {{ status: 'missing' | 'written' | 'empty'; source: string; target: string; keys: string[] }}
 */
export function linkSecrets(opts = {}) {
  const env = opts.env ?? process.env;
  const log = opts.log ?? ((msg) => console.log(msg));
  const here = dirname(fileURLToPath(import.meta.url));
  const target = opts.target ?? join(here, '..', 'apps', 'api', '.dev.vars');
  const source = secretsPath(env);

  if (!existsSync(source)) {
    log(`secrets:link: no secrets file at ${source}; skipping (AI features use their fallbacks).`);
    log(
      'secrets:link: create it (mode 600) with OPENAI_API_KEY / ANTHROPIC_API_KEY to enable live AI.',
    );
    return { status: 'missing', source, target, keys: [] };
  }

  const parsed = parseEnv(readFileSync(source, 'utf8'));
  const keys = WORKER_KEYS.filter((key) => (parsed.get(key) ?? '') !== '');
  if (keys.length === 0) {
    if (existsSync(target)) rmSync(target);
    log(`secrets:link: ${source} has no Worker keys set; removed any stale .dev.vars.`);
    return { status: 'empty', source, target, keys };
  }

  const body = [
    '# Generated by `pnpm secrets:link` from the user-owned secrets file. Do not commit or edit.',
    ...keys.map((key) => `${key}=${quote(/** @type {string} */ (parsed.get(key)))}`),
    '',
  ].join('\n');
  writeFileSync(target, body, { mode: 0o600 });
  chmodSync(target, 0o600);
  log(`secrets:link: wrote ${keys.join(', ')} to ${target}`);
  return { status: 'written', source, target, keys };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    linkSecrets();
  } catch (error) {
    // Never fail the developer's setup over secrets, and never echo file contents.
    console.warn(
      `secrets:link: could not link secrets (${error instanceof Error ? error.message : 'unknown error'}); continuing without them.`,
    );
  }
}
